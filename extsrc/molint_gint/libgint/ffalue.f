      SUBROUTINE FFALUE
      IMPLICIT REAL*8 (A-H,O-Z)
      COMMON/FNTV/W,WS,WT,ONA(100),IA,IPA,IB,IPB,IC,IPC,ID,IPD,
     &  NAP(100),ITIME
      COMMON/FNTVS/WM(3),WN(6)
      COMMON/FNTVT/ONAF(3,100),ONAFG(6,100)
      COMMON/FOCI/VOCI,WOCI,IUX
      IF(IA.EQ.0) GO TO 2
      IF(IPC.EQ.0) GO TO 1
      IF(IUX.NE.0)
     & WRITE(6,102) IA,IPA,IB,IPB,IC,IPC,ID,IPD,W
C     WRITE(6,102) IA,IPA,IB,IPB,IC,IPC,ID,IPD,W,ITIME
      IF(IUX.GE.0)
     & WRITE(6,102) IA,IPA,IB,IPB,IC,IPC,ID,IPD,WOCI
C     WRITE(6,102) IA,IPA,IB,IPB,IC,IPC,ID,IPD,WOCI,ITIME
  102 FORMAT('0    ',8I5,1E22.7,I10)
      RETURN
    1 WRITE(6,103) IA,IPA,IB,IPB,WS,      WT
  103 FORMAT('0    ',4I5,25X,'S =',1E14.7    //50X,'T =',1E14.7)
C   1 WRITE(6,103) IA,IPA,IB,IPB,WS,ITIME,WT
C 103 FORMAT('0    ',4I5,25X,'S =',1E14.7,I10//50X,'T =',1E14.7)
      IF(IPD.EQ.0) GO TO 50
      WRITE(6,500) IPD,(WM(IQ),IQ=1,3)
  500 FORMAT('0',13X,'CENTER',I5,23X,'(X) =',1E14.7/48X,'(Y) =',
     & 1E14.7/48X,'(Z) =',1E14.7)
      WRITE(6,501) (WN(IQ),IQ=1,6)
  501 FORMAT('0',46X,'(XX) =',1E14.7/47X,'(XY) =',1E14.7/47X,
     & '(XZ) =',1E14.7/47X,'(YY) =',1E14.7/47X,'(YZ) =',1E14.7
     & /47X,'(XZ) =',1E14.7/)
   50 IF(IC.EQ.0) RETURN
      DO 10 I=1,IC
      WRITE(6,104) NAP(I),ONA(I)
      IF(ID.EQ.0) GO TO 10
      WRITE(6,105) (ONAF(J,I),J=1,3)
  105 FORMAT('0',47X,'V/X =',1E14.7/48X,'V/Y =',1E14.7/48X,
     &  'V/Z =',1E14.7)
      IF(ID.EQ.1) GO TO 10
      WRITE(6,106) (ONAFG(J,I),J=1,6)
  106 FORMAT('0',46X,'V/XX =',1E14.7/47X,'V/XY =',1E14.7/47X,
     &  'V/XZ =',1E14.7/47X,'V/YY =',1E14.7/47X,'V/YZ =',1E14.7
     &  /47X,'V/ZZ =',1E14.7)
   10 CONTINUE
  104 FORMAT('0',39X,I5,5X,'V =',E14.7)
      RETURN
    2 WRITE(6,200)
      RETURN
  200 FORMAT(/5X,67('*'),' END ')
      END
