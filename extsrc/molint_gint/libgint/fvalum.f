      SUBROUTINE FVALUM(LPOUT)
      IMPLICIT REAL*8 (A-H,O-Z)
      COMMON/FFLA/XA(3),XB(3),XC(3),XD(3),AOE(20),ACE(20),BOE(20),
     &  BCE(20),COE(20),CCE(20),DOE(20),DCE(20),NA(3),NB(3),NC(3),
     &  ND(3),ITA,ITB,ITC,ITD
      COMMON/FAREA/OE(20,102),CE(20,102),XSD(3,100),NQND(4,102),NAO,
     &  NPS,LA,LPA,LB,LPB
      COMMON/FNTV/W,WS,WT,ONA(100),IA,IPA,IB,IPB,IC,IPC,ID,IPD,
     &  NAP(100),ITIME
      DIMENSION NQW(3),CET(20)
      COMMON/FNTVS/WM(3),WN(6)
      COMMON/FNTVT/ONAF(3,100),ONAFG(6,100)
      COMMON/MODPT/ALPHA(10,25),COEFA(10,25),COEFB(102),OEMP(20,102),
     &    CEMP(20,102),NCOMP(102),NTERM(25),NMPOT(10,25),NSIT(100,25),
     &    NPOS(25),NQNDMP(4,102),MPOS(102),IPOS(100,102),IPSET,IOSET,
     &    NCO
      COMMON/FPAR/VFF,XEA(5200),XFA(17,3),XF(17,3),XPA(3,400),
     &  SP(17,3),XQ(3),G1A(400),GG2,AMF(400),MXDT,NAB(3),NCD(3),
     &  NT(3),NKT(3),NTXYM1
      DOUBLE PRECISION VDX
      COMMON /FOCI/ VDX,WOCI,IUX
      EQUIVALENCE (NKT,NTM1),(NKT(2),NTM2),(NKT(3),NTM3)
C   6 CALL CLOCKM(ISTIM)
    6 CONTINUE
      IF((IA-NAO-1)*IA) 7,998,998
    7 IF((IB-NAO-1)*IB) 8,998,998
    8 IF((IPA-NPS-1)*IPA) 9,998,998
    9 IF((IPB-NPS-1)*IPB) 10,998,998
   10 IF(IA.EQ.LA.AND.IB.EQ.LB.AND.IPA.EQ.LPA.AND.IPB.EQ.LPB)
     &  GO TO 24
      CALL FTRA(IA,IPA,1)
      CALL FTRA(IB,IPB,2)
      LA=IA
      LB=IB
      LPA=IPA
      LPB=IPB
      KST=1
   25 IF(IPC.EQ.0) GO TO 11
   24 KST=2
      GO TO 25
   11 CONTINUE
      DO 900 IX=1,NPS
  900 ONA(IX)=0.0D0
      IUX=-1
C *********************** INCLUDE  OVERLAP IMFORMATION **************
   41 SAB=0.0D+00
      DO 30 I=1,3
      NAB(I)=NA(I)+NB(I)
   30 SAB=SAB+(XA(I)-XB(I))**2
      DO 20 IX=1,IPSET
      NPOSIX=NPOS(IX)
      DO 20 IY=1,NPOSIX
      IT=NSIT(IY,IX)
      NAPIT=NAP(IT)
      DO 35 I=1,3
      XC(I)=XSD(I,NAPIT)
   35 NC(I)=0
      NTER=NTERM(IX)
      IF(LPOUT.LT.0)   WRITE(6,800) NAPIT,NTER,IC
  800 FORMAT(' ',3I10,5X,'IN FVALUM')
      IF(NTER.EQ.0) GO TO 20
      U=0.0D0
      DO 100 II=1,NTER
      W=0.0D0
      NIPC=NMPOT(II,IX)
      EPC=ALPHA(II,IX)
      MXD=0
      KT=1
      DO 3 JA=1,ITA
      EPA=AOE(JA)
      DO 3 JB=1,ITB
      EPB=BOE(JB)
      G0=EPA+EPB
      G1=G0+EPC
      AFX=SAB*EPA*EPB/G0
      IF(AFX.GT.100.0D+0) GO TO 3
      MXD=MXD+1
      Q1=0.5D+00/G1
      G1A(MXD)=G1
      SCR=0.0D0
      DO 5 I=1,3
      XPA(I,MXD)=(EPA*XA(I)+EPB*XB(I)+EPC*XC(I))/G1
    5 SCR=SCR+(XC(I)-XPA(I,MXD))**2
      AFX=AFX+EPC*(1.0D0+EPC/G0)*SCR
      IF(AFX.GT.100.0D0) GO TO 45
      AMF(MXD)=DEXP(-AFX)*ACE(JA)*BCE(JB)
      DO 4 I=1,3
      XPI=XPA(I,MXD)
      XEA(KT)=1.0D+00
      IF(NA(I).NE.0) CALL FIAD(XPI-XA(I),XEA(KT),Q1,1,NA(I))
      IF(NB(I).NE.0)
     &  CALL FIAD(XPI-XB(I),XEA(KT),Q1,NA(I)+1,NAB(I))
      NKT(I)=KT
      KT=KT+1+NAB(I)
    4 CONTINUE
      IF(NIPC.EQ.0) GO TO 3
      WP=AMF(MXD)*XEA(NTM1)*XEA(NTM2)*XEA(NTM3)/(DSQRT(G1)*G1)
      W=W+WP
      GO TO 3
   45 MXD=MXD-1
    3 CONTINUE
      IF(NIPC.EQ.0) GO TO 12
      W=W*0.66566768190019485D0
      GO TO 90
   12 MXDT=MXD
      CALL FINTE
   90 U=U+W*COEFA(II,IX)
  100 CONTINUE
      ONA(IT)=ONA(IT)+U
      IF(LPOUT.LT.0)    WRITE(6,9191) IA,IPA,IB,IPB,IT,U
 9191 FORMAT('0',2I5,2X,2I5,2X,I5,F20.6)
   20 CONTINUE
      GO TO 50
  998 WRITE(6,997) IA,IPA,IB,IPB,IC,IPC,ID,IPD
  997 FORMAT(20('*'),'ERROR ***** REQUESTED INTEGRAL',8I5)
      W=1.0D+40
      WS=1.0D+40
      WT=1.0D+40
C  50 CALL CLOCKM(IFTIM)
   50 CONTINUE
C     ITIME=IFTIM-ISTIM
      RETURN
      END
