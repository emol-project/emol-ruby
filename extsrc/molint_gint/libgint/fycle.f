      SUBROUTINE FYCLE
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION XF(17,3),SP(17,3),WW(17),WY(17)
      COMMON/FPAR/V,XEA(5200),XFA(17,3),XFX(17),XFY(17),XFZ(17),
     &  XPA(3,400),SXP(17),SYP(17),SZP(17),XQ(3),G1A(400),G2,
     &  AMF(400),MXDT,NAB(3),NCD(3),NT(3),NTM1,NTM2,NTM3,NTXYM1
      EQUIVALENCE (SXP2,SXP(3)),(SYP2,SYP(3)),(SZP2,SZP(3)),
     &  (SP,SXP),(XF,XFX)
      COMMON/FFDG/XX,FNU( 129),NTSUM1
      DOUBLE PRECISION VDX,UDX,U
      COMMON /FOCI/ VDX,WOCI,IUX
      DIMENSION FNUX(24)
      NTXY=NTM1+NTM2+1
      V=0.0D+00
      VDX=0.0D0
      IF(MXDT.LE.0) RETURN
      KT=1
      DO 5 MXD=1,MXDT
      DO 11 I=1,3
      CALL FIAB(XEA(KT),XFA(1,I),NAB(I),NCD(I),XF(1,I),NT(I))
      KT=KT+1+NAB(I)
      SP(2,I)=XPA(I,MXD)-XQ(I)
      K=NT(I)
      IF(K.LT.3) K=3
      DO 20 J=3,K
   20 SP(J,I)=SP(J-1,I)*SP(2,I)
   11 CONTINUE
      ZGU=G1A(MXD)+G2
      DMU=G1A(MXD)*G2/ZGU
      IF(DMU.LT.1.0D-16) GO TO 26
      S2=SXP2+SYP2+SZP2
      XX=DMU*S2
      DMU=DMU*2.0D+00
      IF(IUX) 101,100,100
  100 XXX=0.
      IF(XX.LE.176.) XXX=DMU*DEXP(-XX)/12.5663706143591728D0
      IF(IUX) 101,102,101
  101 CALL FUXGT
  102 WS=1.0D0
      DO 24 I=1,NTSUM1
      IF(IUX) 103,104,104
  104 FNUX(I)=XXX*WS
      IF(IUX.EQ.0) GO TO 24
  103 FNU(I)=FNU(I)*WS
   24 WS=-WS*DMU
      CALL FFNTA(XFX,NT(1),SXP,WW)
      CALL FFNTA(XFY,NT(2),SYP,WY)
      CALL FIAB(WW,WY,NTM1,NTM2,XFX,NTXY)
      CALL FFNTA(XFZ,NT(3),SZP,XFY)
      CALL FIAB(XFX,XFY,NTXYM1,NTM3,XFZ,NTSUM1)
      GO TO 28
   26 U=XFX(1)*XFY(1)*XFZ(1)
      IF(IUX.LT.0) GO TO 29
      UDX=0.D+0
      IF(XX.LE.100.) UDX=DMU*DEXP(-XX)*U/12.5663706143591728D+0
      GO TO 29
   28 CONTINUE
      U=0.0D+00
      UDX=0.0D0
      DO 333 I=1,NTSUM1
      IF(IUX) 105,106,106
  106 UDX=UDX+FNUX(I)*XFZ(I)
      IF(IUX.EQ.0) GO TO 333
  105 U=U+FNU(I)*XFZ(I)
  333 CONTINUE
   29 AXT=AMF(MXD)/(DSQRT(ZGU)*G1A(MXD))
      IF(IUX) 107,108,108
  108 VDX=VDX+UDX*AXT
      IF(IUX.EQ.0) GO TO 30
  107 V=V+U*AXT
   30 CONTINUE
    5 CONTINUE
      RETURN
      END
