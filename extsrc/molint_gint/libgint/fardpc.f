      SUBROUTINE FARDPC
      COMMON/FNTV/W,WS,WT,ONA(100),IA,IPA,IB,IPB,IC,IPC,ID,IPD,
     &  NAP(100),ITIME
      COMMON/FNTVS/WM(3),WN(6)
      COMMON/FOCI/VOCI,WOCI,IUX
      IF(IA.EQ.0) GO TO 2
      IF(IPC.EQ.0) GO TO 1
      IF(IUX.NE.0)
     & WRITE(7,999) IA,IPA,IB,IPB,IC,IPC,ID,IPD,W
      IF(IUX.GE.0)
     & WRITE(7,999) IA,IPA,IB,IPB,IC,IPC,ID,IPD,WOCI
  999 FORMAT(8I5,E22.7)
      RETURN
    1 CONTINUE
      WRITE(7,500) IA,IPA,IB,IPB,WS,WT
  500 FORMAT(5X,4I5,10X,'S.=',E14.7,5X,'T.=',E14.7)
      IF(IPD.EQ.0) GO TO 5555
      WRITE(7,2050) IA,IPA,IB,IPB,IPD,(WM(IQ),IQ=1,3)
 2050 FORMAT(5I5, 5X,3E14.7,'X',2X,'Y',2X,'Z')
      WRITE(7,2100) IA,IPA,IB,IPB,IPD,(WN(IQ),IQ=1,3)
 2100 FORMAT(5I5,5X,3E14.7,'XX',1X,'XY',1X,'XZ')
      WRITE(7,2150) IA,IPA,IB,IPB,IPD,(WN(IQ),IQ=4,6)
 2150 FORMAT(5I5,5X,3E14.7,'YY',1X,'YZ',1X,'ZZ')
 5555 CONTINUE
      IF(IC.EQ.0) RETURN
      DO 10 I=1,IC
   10 WRITE(7,501) NAP(I),ONA(I)
  501 FORMAT(40X,I5,5X,'V.=',E14.7)
      RETURN
    2 WRITE(7,700)
  700 FORMAT('**********',10X,'END')
      RETURN
      END