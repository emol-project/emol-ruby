      SUBROUTINE FTRA(IA,IPA,K)
      IMPLICIT REAL*8 (A-H,O-Z)
      COMMON/FAREA/OE(20,102),CE(20,102),XSD(3,100),NQND(4,102),NAO,
     &  NPS,LA,LPA,LB,LPB
      COMMON/FFLA/XA(3,4),ACOE(40,4),NA(3,4),ITA(4)
      DO 1 J=1,20
      ACOE(J,K)=OE(J,IA)
    1 ACOE(J+20,K)=CE(J,IA)
      DO 2 J=1,3
      NA(J,K)=NQND(J,IA)
    2 XA(J,K)=XSD(J,IPA)
      ITA(K)=NQND(4,IA)
      RETURN
      END
