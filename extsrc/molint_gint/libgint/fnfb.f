      DOUBLE PRECISION FUNCTION FNFB(NQ,A)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION NQ(3)
      COMMON/FFDG/XX,FNU(24),  DF(24),GICA(81),NTSUM1
      SQA=DSQRT(A)
      N1=NQ(1)+1
      N2=NQ(2)+1
      N3=NQ(3)+1
      FNFB=(2.0D+00*SQA)**(N1+N2+N3-1)/DSQRT(DF(N1)*DF(N2)*DF(N3)*
     &  3.7655850551068593D0*SQA)
      END
